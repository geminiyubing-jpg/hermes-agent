OUT = "/Volumes/DATA/AI-audit/promo-mit-brain/audio-full"

async def gen_one(pid, text):
    mp3 = f"{OUT}/{pid}.mp3"
    words = []
    with open(mp3, "wb") as f:
        async for chunk in edge_tts.Communicate(text, VOICE, rate=RATE, boundary="WordBoundary").stream():
            if chunk["type"] == "audio":
                f.write(chunk["data"])
            elif chunk["type"] == "WordBoundary":
                words.append({"t": chunk["offset"]/1e7, "d": chunk["duration"]/1e7, "w": chunk["text"]})
    json.dump({"pid": pid, "words": words}, open(f"{OUT}/{pid}.words.json", "w"), ensure_ascii=False)
    return len(words)

async def gen():
    manifest = []
    for pid, text in SEGMENTS:
        import os
        if os.path.exists(f"{OUT}/{pid}.words.json"):
            print(pid, "skip (exists)")
            continue
        for attempt in range(5):
            try:
                n = await gen_one(pid, text)
                print(pid, n, "words")
                break
            except Exception as e:
                print(pid, "retry", attempt, e)
                await asyncio.sleep(3 + attempt * 4)
        else:
            raise SystemExit(f"{pid} failed after retries")
    json.dump(manifest, open(f"{OUT}/manifest.json", "w"), ensure_ascii=False, indent=1)

if __name__ == "__main__":
    asyncio.run(gen())
